"""The idempotent knowledge table helpers must emit dialect-correct DDL."""

from __future__ import annotations

from contextlib import contextmanager
from typing import Any

import pytest

from octop.infra.db import migrate


class _RecordingConnection:
    def __init__(self) -> None:
        self.statements: list[str] = []

    def execute(self, sql: str, _params: Any = None) -> None:
        self.statements.append(sql)


class _FakePool:
    def __init__(self, dialect: str) -> None:
        self.dialect = dialect
        self.connection = _RecordingConnection()

    @contextmanager
    def connect(self):
        yield self.connection


@pytest.mark.parametrize(
    "helper",
    [
        migrate._ensure_knowledge_facts_schema,
        migrate._ensure_knowledge_suggestions_schema,
    ],
)
@pytest.mark.parametrize("dialect", ["postgresql", "sqlite"])
def test_knowledge_schema_helpers_use_dialect_ddl(
    helper, dialect: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(migrate, "_table_exists", lambda _db, _name: True)
    db = _FakePool(dialect)
    helper(db)  # type: ignore[arg-type]

    sql = "\n".join(db.connection.statements)
    if dialect == "postgresql":
        assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
        assert "created_at BIGINT NOT NULL" in sql
        assert "AUTOINCREMENT" not in sql
    else:
        assert "INTEGER PRIMARY KEY AUTOINCREMENT" in sql
        assert "created_at INTEGER NOT NULL" in sql
